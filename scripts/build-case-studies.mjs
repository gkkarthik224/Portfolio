import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const studies = JSON.parse(await readFile(resolve(root, 'src/content/case-studies.json'), 'utf8'));
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#39;');
const paragraphs = value => `<p>${escape(value)}</p>`;
const cards = rows => rows.map(row => `<article class="case-panel"><h3>${escape(row.title)}</h3>${paragraphs(row.detail)}</article>`).join('\n');

for (const study of studies) {
  const related = studies.find(item => item.id === study.related);
  if (study.demoUrl && !/^https?:\/\//i.test(study.demoUrl)) throw new Error('demoUrl must be a complete HTTP(S) URL.');
  const demo = study.demoUrl ? `<section class="case-section" aria-labelledby="demo-heading"><p class="case-index">Demonstration</p><h2 id="demo-heading">Video walkthrough</h2><a href="${escape(study.demoUrl)}" target="_blank" rel="noopener noreferrer">Watch the prototype demonstration ↗</a></section>` : '';
  const html = `<!doctype html>
<!-- Generated by scripts/build-case-studies.mjs from src/content/case-studies.json. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <script data-local-preview>if(location.protocol==='file:')location.replace('http://localhost:8080${study.path}');</script>
  <title>${escape(study.title)} | Karthik Krishna</title>
  <meta name="description" content="${escape(study.summary)}">
  <meta property="og:title" content="${escape(study.title)} | Karthik Krishna">
  <meta property="og:description" content="${escape(study.summary)}">
  <link rel="icon" href="/favicon.svg">
  <link rel="stylesheet" href="/page-motion.css?v=2">
  <link rel="stylesheet" href="/local-customizations.css?v=41">
  <link rel="stylesheet" href="/case-study.css?v=1">
  <script src="/smooth-scroll.js?v=1"></script>
  <script src="/page-transitions.js?v=4"></script>
  <script src="/theme-sync.js?v=1"></script>
  <script src="/dot-cursor.js?v=1" defer></script>
  <script src="/skills-page.js?v=10" defer></script>
  <script src="/scroll-text.js?v=1" defer></script>
</head>
<body class="case-page">
  <a class="case-skip" href="#case-content">Skip to case study</a>
  <div id="portfolio-loader" role="status" aria-label="Loading portfolio">
    <div class="portfolio-loader-mark" aria-hidden="true">KK</div>
    <div class="portfolio-loader-caption"><span>KARTHIK KRISHNA</span><span>LOADING PORTFOLIO</span></div>
    <div class="portfolio-loader-track" aria-hidden="true"></div>
  </div>
  <main id="main" class="case-main">
    <header class="case-hero">
      <a class="case-back" href="/portfolio">All projects <span aria-hidden="true">↗</span></a>
      <p class="case-eyebrow">${escape(study.eyebrow)}</p>
      <h1>${escape(study.title)}</h1>
      <p class="case-summary">${escape(study.summary)}</p>
      <dl class="case-facts">
        <div><dt>Status</dt><dd>${escape(study.status)}</dd></div>
        <div><dt>Context</dt><dd>${escape(study.association)}</dd></div>
        <div><dt>My role</dt><dd>${escape(study.role)}</dd></div>
      </dl>
      <p class="case-boundary">${escape(study.boundary)}</p>
    </header>
    <div id="case-content" tabindex="-1">
      ${demo}
      <section class="case-section case-two-column" aria-labelledby="problem-heading">
        <div><p class="case-index">01 / Context</p><h2 id="problem-heading">The problem</h2>${paragraphs(study.problem)}</div>
        <div><h2>My contribution</h2>${paragraphs(study.contribution)}</div>
      </section>
      <section class="case-section" aria-labelledby="workflow-heading">
        <p class="case-index">02 / Workflow</p><h2 id="workflow-heading">From input to outcome</h2>
        <ol class="case-flow" aria-label="High-level workflow">${study.workflow.map(step => `<li><h3>${escape(step.title)}</h3>${paragraphs(step.detail)}</li>`).join('')}</ol>
      </section>
      <section class="case-section" aria-labelledby="architecture-heading">
        <p class="case-index">03 / Architecture</p><h2 id="architecture-heading">Implementation boundaries</h2>
        <div class="case-grid">${cards(study.architecture)}</div>
        <ul class="case-tools" aria-label="Technologies and implementation concepts">${study.tools.map(tool => `<li>${escape(tool)}</li>`).join('')}</ul>
      </section>
      <section class="case-section" aria-labelledby="decisions-heading">
        <p class="case-index">04 / Engineering decisions</p><h2 id="decisions-heading">Controls and trade-offs</h2>
        <div class="case-decisions">${cards(study.decisions)}</div>
      </section>
      <section class="case-section case-result" aria-labelledby="result-heading">
        <p class="case-index">05 / Status and evidence</p><h2 id="result-heading">${escape(study.resultTitle)}</h2>
        ${paragraphs(study.result)}${paragraphs(study.evidence)}
      </section>
      <section class="case-section case-next" aria-labelledby="related-heading">
        <div><p class="case-index">Connected work</p><h2 id="related-heading">${escape(related.title)}</h2><a href="${related.path}">View related case study <span aria-hidden="true">↗</span></a></div>
        <a class="case-cta" href="/contact">Discuss an engineering opportunity <span aria-hidden="true">↗</span></a>
      </section>
    </div>
  </main>
  <footer class="case-footer"><span>Karthik Krishna</span><span>AI · Backend · Automation</span></footer>
</body>
</html>
`;
  const target = resolve(root, study.file);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, html);
  console.log(`Built ${study.path}`);
}
